// The file `kit verify` gives tsc: every catalog claim as one JSX use, and the way back from a
// line tsc complains about to the place in kit.json that made the claim.
//
// Names are pasted only after they pass a pattern and values only through JSON.stringify, so
// nothing from kit.json can change the shape of the file. Example code is the one exception (it
// is code); the caller passes only examples that parse, each already wrapped in a function.

import type { VerifyIssue } from './kit-verify.ts';

/** Inside the catalog folder; tsc prints it like this because it runs there. */
export const KIT_TYPES_FILE = 'build/json/kit-types.tsx';

export type TypesProp = {
  name: string;
  type: string;
  values?: string[] | undefined;
  required?: boolean | undefined;
};

export type TypesComponent = {
  name: string;
  /** The name it has in its module and that module (`import` of kit.json), for the message. */
  exported: string;
  from: string;
  props: TypesProp[];
};

export type TypesExample = {
  /** `Button.1`. */
  key: string;
  /** Place in kit.json: `components.0.examples.0`. */
  path: string;
  /** A whole function declaration around the example's code. */
  source: string;
};

/**
 * What a line of the file stands for.
 * - `import`: the component's import from `@kit`.
 * - `value`: the attribute of one enum value. `value-tag`: the tag of that same use, where tsc
 *   reports a use that matches no overload.
 * - `baseline`: the tag of the use with only the required props. `fill`: one of its props.
 */
export type TypesTarget =
  | { kind: 'import'; path: string; component: string; exported: string; from: string }
  | {
      kind: 'value' | 'value-tag' | 'fill' | 'baseline';
      path: string;
      component: string;
      prop: string;
      value: string;
    }
  | { kind: 'example'; path: string; key: string };

export type KitTypesFile = {
  text: string;
  /** 1-based line to what it stands for; lines without an entry prove nothing by themselves. */
  targets: Record<number, TypesTarget>;
};

const COMPONENT = /^[A-Z][A-Za-z0-9]*$/;
/** A JSX attribute name: an identifier, hyphens allowed inside (`aria-label`). */
const ATTRIBUTE = /^[A-Za-z_$][A-Za-z0-9_$]*(?:-[A-Za-z0-9_$]+)*$/;
/**
 * Accepted by every prop type (`never` is assignable to all of them); keeps a use whole when a
 * required prop has no placeholder.
 */
const ANYTHING = 'undefined as never';

/** The placeholder of a prop by its type; `undefined` when the type has none. */
function placeholder(prop: TypesProp): string | undefined {
  switch (prop.type) {
    case 'string':
    case 'node':
      return '"x"';
    case 'number':
      // Not 0: the contract has no numeric enum, and a prop such as a heading level (1 to 4) is
      // listed as a number.
      return '1';
    case 'boolean':
      return 'true';
    case 'callback':
      return '() => {}';
    case 'element':
      return '<span />';
    case 'enum': {
      const first = prop.values?.[0];
      return first === undefined ? undefined : JSON.stringify(first);
    }
    default:
      return undefined;
  }
}

export function kitTypesSource(
  components: TypesComponent[],
  examples: TypesExample[],
): KitTypesFile {
  const lines: string[] = [];
  const targets: Record<number, TypesTarget> = {};
  const add = (line: string, target?: TypesTarget): void => {
    lines.push(line);
    if (target) targets[lines.length] = target;
  };

  add('// Generated by kitvas for "kit verify". Each use sits on its own lines. Do not edit.');
  const usable = components
    .map((component, index) => ({ component, index }))
    .filter(({ component }) => COMPONENT.test(component.name));
  for (const { component, index } of usable) {
    add(`import { ${component.name} } from "@kit";`, {
      kind: 'import',
      path: `components.${index}.import`,
      component: component.name,
      exported: component.exported,
      from: component.from,
    });
  }
  add('');

  for (const { component, index } of usable) {
    const { name } = component;
    const props = component.props
      .map((prop, propIndex) => ({ prop, path: `components.${index}.props.${propIndex}` }))
      .filter(({ prop }) => ATTRIBUTE.test(prop.name));
    const required = props.filter(({ prop }) => prop.required === true);

    // One use per enum value. The other required props are filled so that only the value is judged.
    for (const { prop, path } of props) {
      if (prop.type !== 'enum') continue;
      for (const value of prop.values ?? []) {
        const about = { path, component: name, prop: prop.name, value };
        add(`void (<${name}`, { kind: 'value-tag', ...about });
        add(`  ${prop.name}={${JSON.stringify(value)}}`, { kind: 'value', ...about });
        for (const other of required) {
          if (other.prop === prop) continue;
          add(`  ${other.prop.name}={${placeholder(other.prop) ?? ANYTHING}}`);
        }
        add('/>);');
      }
    }

    // One use with only the required props. A required prop of a type without a placeholder, or
    // with a name that is no attribute, leaves nothing to prove here.
    const allRequired = component.props.filter((prop) => prop.required === true);
    const fills = required.map(({ prop, path }) => ({ prop, path, text: placeholder(prop) }));
    if (allRequired.length !== required.length || fills.some((fill) => fill.text === undefined)) {
      continue;
    }
    add(`void (<${name}`, {
      kind: 'baseline',
      path: `components.${index}.props`,
      component: name,
      prop: 'props',
      value: `{${required.map(({ prop }) => prop.name).join(', ')}}`,
    });
    for (const { prop, path, text } of fills) {
      add(`  ${prop.name}={${text}}`, {
        kind: 'fill',
        path,
        component: name,
        prop: prop.name,
        value: text ?? '',
      });
    }
    add('/>);');
  }

  for (const example of examples) {
    add('');
    for (const line of example.source.split('\n')) {
      add(line, { kind: 'example', path: example.path, key: example.key });
    }
  }
  add('');
  return { text: lines.join('\n'), targets };
}

/** What tells two messages about the same claim apart from messages about different claims. */
function claim(target: TypesTarget): string {
  switch (target.kind) {
    case 'example':
      return `example ${target.key}`;
    case 'value':
    case 'value-tag':
      return `value ${target.path} ${target.value}`;
    default:
      return `${target.kind} ${target.path}`;
  }
}

/**
 * The issues behind tsc's messages about the generated file, one per claim, in tsc's order.
 * A component whose use with only the required props fails at its tag is missing something every
 * use of it misses, so the tags of its enum uses are not reported again.
 */
export function kitTypeIssues(
  targets: Record<number, TypesTarget>,
  messages: { line: number; text: string }[],
): VerifyIssue[] {
  const brokenBaseline = new Set<string>();
  for (const message of messages) {
    const target = targets[message.line];
    if (target?.kind === 'baseline') brokenBaseline.add(target.component);
  }

  const issues: VerifyIssue[] = [];
  const seen = new Set<string>();
  for (const message of messages) {
    const target = targets[message.line];
    if (!target) continue;
    if (target.kind === 'value-tag' && brokenBaseline.has(target.component)) continue;
    const id = claim(target);
    if (seen.has(id)) continue;
    seen.add(id);

    if (target.kind === 'import') {
      issues.push({
        step: 'types',
        path: target.path,
        key: 'kitIssue.exportMissing',
        params: { name: target.exported, from: target.from },
      });
    } else if (target.kind === 'example') {
      issues.push({
        step: 'types',
        path: target.path,
        key: 'kitIssue.exampleRejected',
        params: { key: target.key, detail: message.text },
      });
    } else {
      issues.push({
        step: 'types',
        path: target.path,
        key: 'kitIssue.propRejected',
        params: {
          component: target.component,
          prop: target.prop,
          value: target.value,
          detail: message.text,
        },
      });
    }
  }
  return issues;
}
