// Generates reference/kit.schema.json, the JSON Schema of kit.json, from the kit contract (the zod
// schema in src/kit/domain/contract.ts). Run it with `npm run kit-schema`; a guard test fails when
// the file is stale (ADR 0081).

import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ComponentSchema,
  ExampleSchema,
  GapSchema,
  KitSchema,
  PropSchema,
  StateEntrySchema,
} from '../src/kit/index.ts';
import { PLUGIN_ROOT } from '../src/shared/env/paths.ts';
import { z } from '../src/shared/index.ts';

/** The file, from the plugin's root, with forward slashes. */
export const KIT_SCHEMA_FILE = 'reference/kit.schema.json';

/** Says where the file comes from, to a person or an agent who opens it. */
const COMMENT =
  'Generated by npm run kit-schema from the kit contract (src/kit/domain/contract.ts). Do not edit it.';

/**
 * The text of reference/kit.schema.json: the shape of kit.json as an agent writes it (a key with a
 * default may be left out), with the parts a rule points at under `$defs`: `component`, `prop`,
 * `stateEntry`, `example` and `gap`.
 */
export function kitSchemaText(): string {
  // The names live in a registry of this script only, so the contract carries no metadata.
  const names = z.registry<{ id: string }>();
  names.add(ComponentSchema, { id: 'component' });
  names.add(PropSchema, { id: 'prop' });
  names.add(StateEntrySchema, { id: 'stateEntry' });
  names.add(ExampleSchema, { id: 'example' });
  names.add(GapSchema, { id: 'gap' });
  const { $schema, ...schema } = z.toJSONSchema(KitSchema, { io: 'input', metadata: names });
  return `${JSON.stringify({ $schema, $comment: COMMENT, ...schema }, null, 2)}\n`;
}

function main(): void {
  writeFileSync(join(PLUGIN_ROOT, ...KIT_SCHEMA_FILE.split('/')), kitSchemaText());
  console.log(`${KIT_SCHEMA_FILE}: written`);
}

if (
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
) {
  main();
}
