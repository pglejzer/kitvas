// Generates docs/adr/README.md from the head lines of the decision records. Run it with `npm run adr`.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLUGIN_ROOT } from '../src/shared/env/paths.ts';

export interface AdrRecord {
  file: string;
  number: string;
  title: string;
  date: string;
  status: string;
  /** The number of the ADR the status names, when it names one. */
  named?: string;
}

export type AdrParse = { ok: true; record: AdrRecord } | { ok: false; problems: string[] };

const FILE_NAME = /^(\d{4})-.+\.md$/;
const TITLE_LINE = /^# (\d{4})\. (.+)$/;
const DATE_LINE = /^Date: (\d{4}-\d{2}-\d{2})\. Status: (.*?)\.(?=\s|$)/;
const PLAIN = /^accepted(?: \(.*\))?$/;
const REPLACED = /^replaced by ADR (\S+)$/;
const CHANGED = /^accepted, changed in part by ADR (\S+)$/;

/** Reads the head of one record: its number, title, date and status, or what is wrong with it. */
export function parseAdr(name: string, text: string): AdrParse {
  const problems: string[] = [];
  const lines = text.split(/\r?\n/);
  const fileNumber = FILE_NAME.exec(name)?.[1];
  if (fileNumber === undefined) problems.push(`${name}: the file name is not NNNN-slug.md`);

  const title = TITLE_LINE.exec(lines[0] ?? '');
  if (title === null) problems.push(`${name}: line 1 is not "# NNNN. Title"`);
  else if (fileNumber !== undefined && title[1] !== fileNumber) {
    problems.push(`${name}: line 1 says ${title[1]}, the file name says ${fileNumber}`);
  }

  const dateLine = lines.find((line) => line.startsWith('Date:'));
  const head = dateLine === undefined ? null : DATE_LINE.exec(dateLine);
  let status = '';
  let named: string | undefined;
  if (dateLine === undefined) problems.push(`${name}: no "Date:" line`);
  else if (head === null)
    problems.push(`${name}: the Date line is not "Date: YYYY-MM-DD. Status: …."`);
  else {
    status = head[2] ?? '';
    const reference = REPLACED.exec(status)?.[1] ?? CHANGED.exec(status)?.[1];
    if (reference !== undefined) {
      if (/^\d{4}$/.test(reference)) named = reference;
      else problems.push(`${name}: the status names "${reference}", not a four digit ADR number`);
    } else if (!PLAIN.test(status)) {
      problems.push(`${name}: the status "${status}" is none of the three forms`);
    }
  }

  if (problems.length > 0 || title === null || head === null) return { ok: false, problems };
  const record: AdrRecord = {
    file: name,
    number: title[1] ?? '',
    title: title[2] ?? '',
    date: head[1] ?? '',
    status,
  };
  if (named !== undefined) record.named = named;
  return { ok: true, record };
}

const cell = (text: string): string => text.replaceAll('|', '\\|');

/** The whole text of docs/adr/README.md, with the records sorted by number. */
export function adrIndex(records: readonly AdrRecord[]): string {
  const rows = [...records]
    .sort((a, b) => a.number.localeCompare(b.number))
    .map(
      (record) =>
        `| [${record.number}](${record.file}) | ${cell(record.title)} | ${record.date} | ${cell(record.status)} |`,
    );
  return [
    '# Decision records',
    '',
    'This file is generated by `npm run adr`. Do not edit it.',
    'An ADR records a decision, not a feature.',
    'A record is never edited, except its status, when a later ADR changes it.',
    'The status is `accepted`, `replaced by ADR NNNN` (the later record took its place) or `accepted, changed in part by ADR NNNN` (the later record changed a part of it).',
    '',
    '| ADR | Title | Date | Status |',
    '| --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

function main(): void {
  const dir = join(PLUGIN_ROOT, 'docs', 'adr');
  const names = readdirSync(dir)
    .filter((name) => name.endsWith('.md') && name !== 'README.md')
    .sort();
  const records: AdrRecord[] = [];
  const problems: string[] = [];
  for (const name of names) {
    const parsed = parseAdr(name, readFileSync(join(dir, name), 'utf8'));
    if (parsed.ok) records.push(parsed.record);
    else problems.push(...parsed.problems);
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
  writeFileSync(join(dir, 'README.md'), adrIndex(records));
  console.log(`docs/adr/README.md: ${records.length} records`);
}

if (
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
) {
  main();
}
