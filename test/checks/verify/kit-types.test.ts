import assert from 'node:assert/strict';
import { test } from 'node:test';
import {
  KIT_TYPES_FILE,
  kitTypeIssues,
  kitTypesSource,
  type TypesComponent,
  type TypesExample,
} from '../../../src/checks/domain/kit/kit-types.ts';

const BUTTON: TypesComponent = {
  name: 'Button',
  exported: 'Button',
  from: '@acme/ui',
  props: [
    { name: 'variant', type: 'enum', values: ['solid', 'ghost'] },
    { name: 'children', type: 'node', required: true },
  ],
};

/** A required prop without a placeholder: no use with only the required props. */
const TABLE: TypesComponent = {
  name: 'Table',
  exported: 'default',
  from: '@acme/ui/Table',
  props: [
    { name: 'rows', type: 'object', required: true },
    { name: 'density', type: 'enum', values: ['compact'] },
  ],
};

const EXAMPLE: TypesExample = {
  key: 'Button.1',
  path: 'components.0.examples.0',
  source: 'function KitvasExample0() {\n  return (<>\n<Button>Save</Button>\n</>);\n}',
};

const FILE = kitTypesSource([BUTTON, TABLE], [EXAMPLE]);

test('the file is in the catalog folder, where tsc runs', () => {
  assert.equal(KIT_TYPES_FILE, 'build/json/kit-types.tsx');
});

test('every enum value, the required props and every example get lines of their own', () => {
  assert.equal(
    FILE.text,
    [
      '// Generated by kitvas for "kit verify". Each use sits on its own lines. Do not edit.',
      'import { Button } from "@kit";',
      'import { Table } from "@kit";',
      '',
      'void (<Button',
      '  variant={"solid"}',
      '  children={"x"}',
      '/>);',
      'void (<Button',
      '  variant={"ghost"}',
      '  children={"x"}',
      '/>);',
      'void (<Button',
      '  children={"x"}',
      '/>);',
      'void (<Table',
      '  density={"compact"}',
      '  rows={undefined as never}',
      '/>);',
      '',
      'function KitvasExample0() {',
      '  return (<>',
      '<Button>Save</Button>',
      '</>);',
      '}',
      '',
    ].join('\n'),
  );
});

test('each line that makes a claim leads back to its place in kit.json', () => {
  const variant = { path: 'components.0.props.0', component: 'Button', prop: 'variant' };
  const density = {
    path: 'components.1.props.1',
    component: 'Table',
    prop: 'density',
    value: 'compact',
  };
  const example = { kind: 'example', path: 'components.0.examples.0', key: 'Button.1' };
  assert.deepEqual(FILE.targets, {
    2: {
      kind: 'import',
      path: 'components.0.import',
      component: 'Button',
      exported: 'Button',
      from: '@acme/ui',
    },
    3: {
      kind: 'import',
      path: 'components.1.import',
      component: 'Table',
      exported: 'default',
      from: '@acme/ui/Table',
    },
    5: { kind: 'value-tag', ...variant, value: 'solid' },
    6: { kind: 'value', ...variant, value: 'solid' },
    9: { kind: 'value-tag', ...variant, value: 'ghost' },
    10: { kind: 'value', ...variant, value: 'ghost' },
    13: {
      kind: 'baseline',
      path: 'components.0.props',
      component: 'Button',
      prop: 'props',
      value: '{children}',
    },
    14: {
      kind: 'fill',
      path: 'components.0.props.1',
      component: 'Button',
      prop: 'children',
      value: '"x"',
    },
    16: { kind: 'value-tag', ...density },
    17: { kind: 'value', ...density },
    21: example,
    22: example,
    23: example,
    24: example,
    25: example,
  });
});

test('required props are filled by their type', () => {
  const all: TypesComponent = {
    name: 'Field',
    exported: 'Field',
    from: 'x',
    props: [
      { name: 'label', type: 'string', required: true },
      { name: 'rows', type: 'number', required: true },
      { name: 'open', type: 'boolean', required: true },
      { name: 'icon', type: 'element', required: true },
      { name: 'onChange', type: 'callback', required: true },
      { name: 'size', type: 'enum', values: ['sm', 'md'], required: true },
      { name: 'aria-label', type: 'string', required: true },
      { name: 'hint', type: 'string' },
    ],
  };
  const { text } = kitTypesSource([all], []);
  const baseline = text.slice(text.lastIndexOf('void (<Field'));
  assert.equal(
    baseline,
    [
      'void (<Field',
      '  label={"x"}',
      '  rows={1}',
      '  open={true}',
      '  icon={<span />}',
      '  onChange={() => {}}',
      '  size={"sm"}',
      '  aria-label={"x"}',
      '/>);',
      '',
    ].join('\n'),
  );
  // The enum's own uses: the value under test is not filled a second time.
  assert.ok(text.includes('void (<Field\n  size={"md"}\n  label={"x"}\n  rows={1}\n'));
  assert.equal(text.split('size={"md"}').length, 2);
});

test('a component without required props is used bare; values are written as JSON', () => {
  const plain: TypesComponent = {
    name: 'Divider',
    exported: 'Divider',
    from: 'x',
    props: [{ name: 'label', type: 'enum', values: ['a"b', '</x>{'] }],
  };
  const { text, targets } = kitTypesSource([plain], []);
  assert.ok(text.includes('  label={"a\\"b"}\n'));
  assert.ok(text.includes('  label={"</x>{"}\n'));
  assert.ok(text.endsWith('void (<Divider\n/>);\n'));
  const baseline = Object.values(targets).find((target) => target.kind === 'baseline');
  assert.deepEqual(baseline, {
    kind: 'baseline',
    path: 'components.0.props',
    component: 'Divider',
    prop: 'props',
    value: '{}',
  });
});

test('names that are no component or attribute names never reach the file', () => {
  const odd: TypesComponent[] = [
    { name: 'x /><script>', exported: 'x', from: 'x', props: [] },
    {
      name: 'Safe',
      exported: 'Safe',
      from: 'x',
      props: [
        { name: 'a b={1}', type: 'enum', values: ['v'] },
        { name: 'on click', type: 'string', required: true },
        { name: 'tone', type: 'enum', values: ['info'] },
      ],
    },
  ];
  const { text, targets } = kitTypesSource(odd, []);
  assert.equal(
    text,
    [
      '// Generated by kitvas for "kit verify". Each use sits on its own lines. Do not edit.',
      'import { Safe } from "@kit";',
      '',
      'void (<Safe',
      '  tone={"info"}',
      '/>);',
      '',
    ].join('\n'),
  );
  // The component keeps its index in kit.json, and has no use with only the required props.
  assert.deepEqual(
    Object.values(targets).map((target) => `${target.kind} ${target.path}`),
    ['import components.1.import', 'value-tag components.1.props.2', 'value components.1.props.2'],
  );
});

test('messages become one issue per claim, with the tsc text as the detail', () => {
  const issues = kitTypeIssues(FILE.targets, [
    { line: 3, text: 'Module has no exported member Table.' },
    { line: 6, text: 'Type "solid" is not assignable.' },
    { line: 5, text: 'No overload matches this call.' },
    { line: 10, text: 'Type "ghost" is not assignable.' },
    { line: 14, text: 'Type string is not assignable to type number.' },
    { line: 23, text: 'Property size does not exist.' },
    { line: 22, text: 'A second message about the same example.' },
    // A fill inside an enum use and a closing line prove nothing by themselves.
    { line: 7, text: 'ignored' },
    { line: 8, text: 'ignored' },
    { line: 99, text: 'ignored' },
  ]);
  assert.deepEqual(issues, [
    {
      step: 'types',
      path: 'components.1.import',
      key: 'kitIssue.exportMissing',
      params: { name: 'default', from: '@acme/ui/Table' },
    },
    {
      step: 'types',
      path: 'components.0.props.0',
      key: 'kitIssue.propRejected',
      params: {
        component: 'Button',
        prop: 'variant',
        value: 'solid',
        detail: 'Type "solid" is not assignable.',
      },
    },
    {
      step: 'types',
      path: 'components.0.props.0',
      key: 'kitIssue.propRejected',
      params: {
        component: 'Button',
        prop: 'variant',
        value: 'ghost',
        detail: 'Type "ghost" is not assignable.',
      },
    },
    {
      step: 'types',
      path: 'components.0.props.1',
      key: 'kitIssue.propRejected',
      params: {
        component: 'Button',
        prop: 'children',
        value: '"x"',
        detail: 'Type string is not assignable to type number.',
      },
    },
    {
      step: 'types',
      path: 'components.0.examples.0',
      key: 'kitIssue.exampleRejected',
      params: { key: 'Button.1', detail: 'Property size does not exist.' },
    },
  ]);
});

test('a use that matches no overload is reported at its tag', () => {
  assert.deepEqual(
    kitTypeIssues(FILE.targets, [{ line: 9, text: 'No overload matches this call.' }]),
    [
      {
        step: 'types',
        path: 'components.0.props.0',
        key: 'kitIssue.propRejected',
        params: {
          component: 'Button',
          prop: 'variant',
          value: 'ghost',
          detail: 'No overload matches this call.',
        },
      },
    ],
  );
});

test('a component that fails with only its required props is reported once, not per value', () => {
  const issues = kitTypeIssues(FILE.targets, [
    { line: 5, text: 'Property label is missing.' },
    { line: 9, text: 'Property label is missing.' },
    { line: 10, text: 'Type "ghost" is not assignable.' },
    { line: 13, text: 'Property label is missing.' },
    // Table has no such use, so its tag still counts.
    { line: 16, text: 'Property caption is missing.' },
  ]);
  assert.deepEqual(
    issues.map((issue) => [issue.path, issue.params.prop, issue.params.value, issue.params.detail]),
    [
      ['components.0.props.0', 'variant', 'ghost', 'Type "ghost" is not assignable.'],
      ['components.0.props', 'props', '{children}', 'Property label is missing.'],
      ['components.1.props.1', 'density', 'compact', 'Property caption is missing.'],
    ],
  );
});
